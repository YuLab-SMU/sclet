sclet_ai_error <- function(class, message, parent = NULL) {
    condition <- structure(
        list(message = message, call = NULL, parent = parent),
        class = c(class, "sclet_ai_error", "error", "condition")
    )
    stop(condition)
}

sclet_ai_normalize_list_field <- function(value) {
    if (is.null(value)) return(list())
    if (is.list(value)) return(value)
    as.list(value)
}

sclet_ai_normalize_findings <- function(findings) {
    findings <- sclet_ai_normalize_list_field(findings)
    lapply(findings, function(finding) {
        if (is.list(finding)) return(finding)
        list(
            statement = as.character(finding)[[1L]],
            severity = "info",
            claim_level = "hypothesis",
            evidence_refs = character()
        )
    })
}


#' Construct a structured sclet AI result
#'
#' @param answer Optional natural-language answer.
#' @param findings List of structured findings.
#' @param evidence Evidence references or summaries.
#' @param warnings Warnings generated by the adapter or validator.
#' @param recommendations Recommended next steps.
#' @param proposed_actions Proposed, but not automatically executed, actions.
#' @param context Context metadata or a full AI context.
#' @param metadata Model and call metadata.
#' @return An object of class `sclet_ai_result`.
new_sclet_ai_result <- function(
    task,
    answer = NULL,
    findings = list(),
    evidence = list(),
    warnings = list(),
    recommendations = list(),
    proposed_actions = list(),
    context = NULL,
    metadata = list()
) {
    if (!is.character(task) || length(task) != 1L || is.na(task) || !nzchar(task)) {
        stop("`task` must be a single non-empty character string.")
    }
    findings <- sclet_ai_normalize_findings(findings)
    evidence <- sclet_ai_normalize_list_field(evidence)
    warnings <- sclet_ai_normalize_list_field(warnings)
    recommendations <- sclet_ai_normalize_list_field(recommendations)
    proposed_actions <- sclet_ai_normalize_list_field(proposed_actions)
    result <- list(
        task = task,
        answer = if (is.null(answer)) NULL else as.character(answer)[[1L]],
        findings = if (is.null(findings)) list() else findings,
        evidence = if (is.null(evidence)) list() else evidence,
        warnings = if (is.null(warnings)) list() else warnings,
        recommendations = if (is.null(recommendations)) list() else recommendations,
        proposed_actions = if (is.null(proposed_actions)) list() else proposed_actions,
        context = context,
        metadata = metadata
    )
    class(result) <- c("sclet_ai_result", "list")
    validate_sclet_ai_result(result)
    result
}

#' Validate a structured sclet AI result
#'
#' @param result An object returned by `new_sclet_ai_result()`.
#' @param error Logical. If `TRUE`, stop on invalid output.
#' @return `TRUE` invisibly when valid, or a character vector of problems.
validate_sclet_ai_result <- function(result, error = TRUE) {
    problems <- character()
    required <- c("task", "findings", "evidence", "warnings", "recommendations", "proposed_actions")
    if (!is.list(result)) {
        problems <- c(problems, "result must be a list")
    } else {
        problems <- c(problems, setdiff(required, names(result)))
        if (is.null(result$task) || length(result$task) != 1L || !is.character(result$task)) {
            problems <- c(problems, "task must be a single character value")
        }
        for (field in c("findings", "evidence", "warnings", "recommendations", "proposed_actions")) {
            if (!is.list(result[[field]])) {
                problems <- c(problems, paste0(field, " must be a list"))
            }
        }
        if (is.list(result$findings) && length(result$findings)) {
            allowed_severity <- c("info", "low", "warning", "high", "error")
            allowed_claim <- c(
                "observed", "measured", "estimated", "associated",
                "consistent_with", "suggestive", "hypothesis", "causal"
            )
            for (i in seq_along(result$findings)) {
                finding <- result$findings[[i]]
                if (!is.list(finding)) {
                    problems <- c(problems, paste0("findings[[", i, "]] must be a list"))
                    next
                }
                if (!is.null(finding$severity) && !finding$severity %in% allowed_severity) {
                    problems <- c(problems, paste0("findings[[", i, "]] has invalid severity"))
                }
                if (!is.null(finding$claim_level) && !finding$claim_level %in% allowed_claim) {
                    problems <- c(problems, paste0("findings[[", i, "]] has invalid claim_level"))
                }
                if (identical(finding$claim_level, "causal") && is.null(finding$evidence_refs)) {
                    problems <- c(problems, paste0("findings[[", i, "]] causal claim requires evidence_refs"))
                }
            }
        }
    }
    problems <- unique(problems[nzchar(problems)])
    if (length(problems) && isTRUE(error)) {
        sclet_ai_error(
            "sclet_ai_invalid_output",
            paste("Invalid sclet AI result:", paste(problems, collapse = "; "))
        )
    }
    if (length(problems)) problems else TRUE
}

#' @export
print.sclet_ai_result <- function(x, ...) {
    cat("sclet AI result [", x$task, "]\n", sep = "")
    if (!is.null(x$answer) && nzchar(x$answer)) {
        cat(x$answer, "\n", sep = "")
    }
    cat("Findings:", length(x$findings),
        " Recommendations:", length(x$recommendations),
        " Proposed actions:", length(x$proposed_actions), "\n", sep = "")
    invisible(x)
}

sclet_ai_normalize_response <- function(response, task, context, metadata = list()) {
    if (inherits(response, "sclet_ai_result")) {
        response$context <- response$context %||% list(
            schema_version = context$schema_version,
            fingerprint = context$fingerprint
        )
        response$metadata <- utils::modifyList(response$metadata %||% list(), metadata)
        validate_sclet_ai_result(response)
        return(response)
    }
    if (is.character(response)) {
        return(new_sclet_ai_result(
            task = task,
            answer = paste(response, collapse = "\n"),
            context = list(
                schema_version = context$schema_version,
                fingerprint = context$fingerprint
            ),
            metadata = metadata
        ))
    }
    if (is.list(response)) {
        fields <- c("answer", "findings", "evidence", "warnings", "recommendations", "proposed_actions")
        values <- response[intersect(fields, names(response))]
        values$task <- task
        values$context <- response$context %||% list(
            schema_version = context$schema_version,
            fingerprint = context$fingerprint
        )
        values$metadata <- utils::modifyList(metadata, response$metadata %||% list())
        return(do.call(new_sclet_ai_result, values))
    }
    sclet_ai_error("sclet_ai_invalid_output", "AI response must be text, a list, or sclet_ai_result.")
}
